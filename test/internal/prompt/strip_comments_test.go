package prompt_test

import (
	"strings"
	"testing"

	"github.com/maimuzo/continuo/internal/prompt"
)

// 目的: コメントを取り除く処理と、空になった見出しを落とす処理の境目を固定する
// （#188（エージェントへ送る指示書が長く、順序も強調も揃っていないため、初見で読み取れない）。
// [docs/plans/continuo_design.md] の 5-3m）。
//
// **8つのうち5つは、敵対的レビューが実機で再現させた欠陥である。**
// どれも「利用者が書いた文が、警告も出ずに送る文面から消える」形をしていた。
//
//	行頭の井桁つき番号が残る       … `#188 …` を深さ1の見出しとみなし、行ごと消していた
//	閉じ忘れが本文を飲まない       … `-->` を1つ打ち忘れると、そこから断片の終わりまで全部消えていた
//	行内コメントの後ろの本文が残る … `<!-- 補足 --> 本文` の本文まで消えていた
//	古い ## の本文でも 4-4 が残る  … この版より前の WORKFLOW.md を持つ利用者全員で、区切りの見出しが消えていた
//	コメントの中の囲みは落ちる     … コメントアウトした手順が、生きた指示として送られていた
//
// 与える情報: 8通りの本文。
// 成功条件: 残ってほしいものが残り、消えてほしいものが消えること。
func TestBuild_コメントと空の見出しの境目(t *testing.T) {
	for _, tc := range []struct {
		name string
		// body は WORKFLOW.md の front matter より後ろである。
		body string
		// want は、送る文面に残っていてほしい文字列である。
		want []string
		// unwant は、送る文面から消えていてほしい文字列である。
		unwant []string
	}{
		{"行頭の井桁つき番号が残る",
			"### 参考\n\n過去の議論はここにあります。\n\n#188 の議論を必ず読んでください\n",
			[]string{"188 の議論を必ず読んでください", "### 参考"}, nil},
		{"閉じ忘れが本文を飲まない",
			"### 前置き\n\nここは残ってほしい。\n\n<!-- ここから先はメモ\nまだ書きかけ\n\n### 必ず守ること\n\n秘密鍵を絶対に読まないでください。\n",
			[]string{"### 必ず守ること", "秘密鍵を絶対に読まないでください"}, nil},
		{"行内コメントの後ろの本文が残る",
			"### 決まり\n\n<!-- 補足 --> 必ず日本語で書いてください。\n",
			[]string{"必ず日本語で書いてください", "### 決まり"}, []string{"補足"}},
		{"古い ## の本文でも 4-4 が残る",
			"## 何をする作業か\n\nこの issue は実装してください。\n",
			[]string{"## 4-4. このプロジェクトの決まり", "## 何をする作業か"}, nil},
		{"囲みの中のコメントは残る",
			"### 囲んだ\n\n```\n<!-- これは送りたい -->\n```\n",
			[]string{"これは送りたい"}, nil},
		{"コメントの中の囲みは落ちる",
			"### コメントの中\n\n<!--\n下は例です\n```\necho ZZPROBE_INSIDE_COMMENT\n```\n-->\n\n中身です。\n",
			[]string{"中身です"}, []string{"ZZPROBE_INSIDE_COMMENT", "下は例です"}},
		{"案内のコメントだけの節は落ちる",
			"### テストの走らせ方\n\n<!-- ここに書いてください -->\n",
			nil, []string{"### テストの走らせ方"}},
		{"空になった親も落ちる",
			"## 親\n\n### 子\n\n<!-- ここに書いてください -->\n",
			nil, []string{"## 親", "### 子"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			got := prompt.Build(tc.body, "/tmp/WORKFLOW.md").Text()
			for _, w := range tc.want {
				if !strings.Contains(got, w) {
					t.Errorf("%q が消えています", w)
				}
			}
			for _, u := range tc.unwant {
				if strings.Contains(got, u) {
					t.Errorf("%q が残っています", u)
				}
			}
		})
	}
}
